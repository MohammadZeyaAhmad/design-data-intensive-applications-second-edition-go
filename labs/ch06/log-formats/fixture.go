func Schema(namespace string) string {
	ns := pgx.Identifier{namespace}.Sanitize()
	return fmt.Sprintf(`CREATE SCHEMA %s;
CREATE TABLE %s.stock(tenant_id text NOT NULL,warehouse_id text NOT NULL,sku text NOT NULL,
quantity bigint NOT NULL CHECK(quantity>=0),payload text NOT NULL,nullable_text text,
recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),PRIMARY KEY(tenant_id,warehouse_id,sku));
CREATE TABLE %s.receipts(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,request_key text NOT NULL UNIQUE,
sku text NOT NULL,quantity bigint NOT NULL CHECK(quantity>0),recorded_at timestamptz NOT NULL DEFAULT clock_timestamp(),
day_label date NOT NULL DEFAULT current_date,sample bigint NOT NULL DEFAULT 0);
CREATE TABLE %s.scratch(id text PRIMARY KEY,quantity bigint NOT NULL);
CREATE TABLE %s.barriers(id text PRIMARY KEY);`, ns, ns, ns, ns, ns)
}

