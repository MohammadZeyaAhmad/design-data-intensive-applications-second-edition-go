type State struct {
	Rows          map[string][]json.RawMessage `json:"rows"`
	Digest        string                       `json:"sha256"`
	Receipts      int                          `json:"receipts"`
	StockQuantity int64                        `json:"book_quantity"`
	PayloadHash   string                       `json:"book_payload_sha256"`
}

func ReadState(ctx context.Context, dsn string) (State, error) {
	conn, err := pgx.Connect(ctx, dsn)
	if err != nil {
		return State{}, fmt.Errorf("state endpoint unavailable")
	}
	defer conn.Close(context.Background())
	if _, err = conn.Exec(ctx, "SET timezone='UTC'"); err != nil {
		return State{}, err
	}
	s := State{Rows: map[string][]json.RawMessage{}}
	for _, table := range tables {
		order := "id"
		if table == "stock" {
			order = "tenant_id,warehouse_id,sku"
		}
		rows, err := conn.Query(ctx, "SELECT to_jsonb(t)::text FROM "+pgx.Identifier{"log_lab", table}.Sanitize()+" t ORDER BY "+order)
		if err != nil {
			return s, err
		}
		entries := []json.RawMessage{}
		for rows.Next() {
			var body string
			if err = rows.Scan(&body); err != nil {
				rows.Close()
				return s, err
			}
			entries = append(entries, json.RawMessage(body))
		}
		err = rows.Err()
		rows.Close()
		if err != nil {
			return s, err
		}
		s.Rows[table] = entries
	}
	var payload string
	if err = conn.QueryRow(ctx, "SELECT quantity,payload FROM log_lab.stock WHERE sku='BOOK'").Scan(&s.StockQuantity, &payload); err != nil {
		return s, err
	}
	h := sha256.Sum256([]byte(payload))
	s.PayloadHash = hex.EncodeToString(h[:])
	s.Receipts = len(s.Rows["receipts"])
	body, _ := json.Marshal(s.Rows)
	digest := sha256.Sum256(body)
	s.Digest = hex.EncodeToString(digest[:])
	return s, nil
}
func FieldsOfReceipt(ctx context.Context, dsn, namespace string) (map[string]string, error) {
	conn, err := pgx.Connect(ctx, dsn)
	if err != nil {
		return nil, err
	}
	defer conn.Close(context.Background())
	var body string
	if err = conn.QueryRow(ctx, "SELECT to_jsonb(r)::text FROM "+pgx.Identifier{namespace, "receipts"}.Sanitize()+" r WHERE request_key='statement-replay'").Scan(&body); err != nil {
		return nil, err
	}
	var values map[string]any
	if err = json.Unmarshal([]byte(body), &values); err != nil {
		return nil, err
	}
	fields := map[string]string{}
	for _, name := range []string{"id", "recorded_at", "day_label", "sample"} {
		fields[name] = fmt.Sprint(values[name])
	}
	return fields, nil
}
func TableSignature(r Relation) string {
	names := []string{}
	for _, c := range r.Columns {
		names = append(names, fmt.Sprintf("%s:%d:%d", c.Name, c.OID, c.Modifier))
	}
	return r.Qualified() + "(" + strings.Join(names, ",") + ")"
}
