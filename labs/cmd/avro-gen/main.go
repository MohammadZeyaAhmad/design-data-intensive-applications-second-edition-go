// avro-gen emits plain structs for this repository's finite snapshot profile.
// Binary encoding and schema resolution remain in the pinned Avro runtime.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"go/token"
	"os"
	"sort"
	"strconv"
	"strings"

	"github.com/MohammadZeyaAhmad/design-data-intensive-applications-second-edition-go/labs/internal/avroprofile"
	"github.com/twmb/avro"
)

func main() {
	if e := run(); e != nil {
		fmt.Fprintln(os.Stderr, e)
		os.Exit(1)
	}
}
func goName(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if p != "" {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}
func run() error {
	source := flag.String("schema", "", "canonical .avsc path")
	pkg := flag.String("package", "", "generated package")
	output := flag.String("output", "", "Go output path")
	flag.Parse()
	if flag.NArg() != 0 || !token.IsIdentifier(*pkg) || *source == "" || *output == "" {
		return fmt.Errorf("usage: avro-gen -schema file -package name -output file")
	}
	raw, e := os.ReadFile(*source)
	if e != nil {
		return e
	}
	schema, _, _, e := avroprofile.Compile(raw)
	if e != nil {
		return e
	}
	declarations := map[string]string{}
	var typ func(*avro.SchemaNode) (string, error)
	typ = func(n *avro.SchemaNode) (string, error) {
		switch n.Type {
		case "string":
			return "string", nil
		case "boolean":
			return "bool", nil
		case "int":
			return "int32", nil
		case "long":
			return "int64", nil
		case "array":
			t, e := typ(n.Items)
			return "[]" + t, e
		case "map":
			t, e := typ(n.Values)
			return "map[string]" + t, e
		case "union":
			if len(n.Branches) != 2 {
				return "", fmt.Errorf("generator supports nullable unions only")
			}
			for i := range n.Branches {
				if n.Branches[i].Type != "null" {
					t, e := typ(&n.Branches[i])
					other := 1 - i
					if n.Branches[other].Type != "null" {
						return "", fmt.Errorf("generator requires a null branch")
					}
					return "*" + t, e
				}
			}
			return "", fmt.Errorf("empty union")
		case "record":
			name := goName(n.Name)
			if strings.Contains(name, ".") {
				parts := strings.Split(name, ".")
				name = parts[len(parts)-1]
			}
			if !token.IsIdentifier(name) {
				return "", fmt.Errorf("invalid generated name")
			}
			var b bytes.Buffer
			fmt.Fprintf(&b, "type %s struct {\n", name)
			seen := map[string]bool{}
			for _, f := range n.Fields {
				field := goName(f.Name)
				if !token.IsIdentifier(field) || seen[field] {
					return "", fmt.Errorf("ambiguous generated field")
				}
				seen[field] = true
				t, e := typ(&f.Type)
				if e != nil {
					return "", e
				}
				fmt.Fprintf(&b, "%s %s `avro:%s`\n", field, t, strconv.Quote(f.Name))
			}
			b.WriteString("}\n")
			text := b.String()
			if old, ok := declarations[name]; ok && old != text {
				return "", fmt.Errorf("colliding generated type")
			}
			declarations[name] = text
			return name, nil
		default:
			return "", fmt.Errorf("unsupported generator type: %s", n.Type)
		}
	}
	if _, e = typ(schema.Root()); e != nil {
		return e
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by the repository avro-gen; DO NOT EDIT.\npackage %s\n", *pkg)
	names := make([]string, 0, len(declarations))
	for name := range declarations {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		b.WriteString(declarations[name])
	}
	goSource, e := format.Source(b.Bytes())
	if e != nil {
		return e
	}
	return os.WriteFile(*output, goSource, 0644)
}
